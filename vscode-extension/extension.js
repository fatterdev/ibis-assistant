/**
 * Load ESM ide-host via its package exports (monorepo/dev) or the vendored copy
 * generated by scripts/sync-ide-host.mjs into a packaged VSIX.
 */
async function loadIdeHost() {
  try {
    const host = await import("@ibis/ide-host");
    const lmRpc = await import("@ibis/ide-host/lm-rpc");
    return { ...host, ...lmRpc, source: "package" };
  } catch (err) {
    logLine(
      `ide-host package import failed (${err && err.message ? err.message : err}); using vendored copy`,
    );
    const host = await import("./vendor/ide-host/index.js");
    const lmRpc = await import("./vendor/ide-host/lm-rpc.js");
    return { ...host, ...lmRpc, source: "vendor" };
  }
}

function logLine(message) {
  const line = `[${new Date().toISOString()}] ${message}`;
  if (outputChannel) {
    outputChannel.appendLine(line);
  }
  appendUiTestLog(line);
}

/**
 * Mirror every Output-channel line to a local file so a test run leaves a
 * persistable evidence trail (the S1.3 analysis lost its channel numbers to
 * exactly this gap). Swallows failures — the sink must never break the
 * extension.
 */
function appendUiTestLog(line) {
  try {
    fs.mkdirSync(UI_TEST_LOG_DIR, { recursive: true });
    fs.appendFileSync(UI_TEST_LOG_PATH, `${line}\n`);
  } catch {
    /* ignore */
  }
}

/** Boot separator written to the sink file only, delimiting runs. */
function startUiTestLog(version) {
  appendUiTestLog(`\n===== ibis-assistant ${version} boot ${new Date().toISOString()} =====`);
}

function logVerbose(cfg, message) {
  if (cfg.get("debug.verboseLogging", false)) {
    logLine(message);
  }
}

function getConfig() {
  return vscode.workspace.getConfiguration("ibis");
}

/**
 * True when the user set the key explicitly in any settings scope.
 * @param {vscode.WorkspaceConfiguration} cfg
 * @param {string} key
 */
function isExplicitlyConfigured(cfg, key) {
  const inspected = cfg.inspect(key);
  if (!inspected) {
    return false;
  }
  return [inspected.globalValue, inspected.workspaceValue, inspected.workspaceFolderValue].some(
    (v) => v !== undefined,
  );
}

/**
 * Precedence: explicit VS Code setting > environment variable > setting default.
 * @param {vscode.WorkspaceConfiguration} cfg
 * @param {string} key
 * @param {string} envName
 * @param {string | number | undefined} fallback
 */
function settingOrEnv(cfg, key, envName, fallback) {
  if (isExplicitlyConfigured(cfg, key)) {
    return cfg.get(key, fallback);
  }
  const envValue = (process.env[envName] || "").trim();
  if (envValue) {
    return envValue;
  }
  return cfg.get(key, fallback);
}

/**
 * @param {vscode.ExtensionContext} context
 */
async function activate(context) {
  outputChannel = vscode.window.createOutputChannel("Ibis Assistant");
  context.subscriptions.push(outputChannel);
  startUiTestLog(context.extension.packageJSON.version);

  let host;
  try {
    host = await loadIdeHost();
  } catch (err) {
    const message = err && err.message ? err.message : err;
    logLine(`ide-host unavailable: ${message}`);
    vscode.window.showErrorMessage(`Ibis Assistant could not load its runtime host: ${message}`);
    return;
  }

  const cfg = getConfig();
  bindHostDispose(host);
  // The VSIX spawns a plugin child only in explicit `spawn` mode now; the
  // dual-child warning targets that spawn + daemon/plugin combination.
  if (resolveBackendSelection(cfg, host).mode === "spawn") {
    host.warnDualPluginChildren();
  }

  await startLmBridge(host, cfg);
  registerMcpProvider(context, host);
  createStatusBarItem(context, host);
  const treeApi = { getConfig, resolveBackend, logLine };
  registerMemoryTree(context, treeApi, host);
  registerWorkstreamTree(context, treeApi, host);
  registerCurationMenu(context, treeApi, host);
  registerQuickActions(context);
  registerRememberSelection(
    context,
    { getConfig, resolveBackend, logLine, kinds: REMEMBER_KINDS },
    host,
  );
  prewarmRuntime(host, cfg);

  context.subscriptions.push(
    vscode.commands.registerCommand("ibis.openSettings", async () => {
      try {
        const url = await resolveSettingsURL(host, await resolveBackend(host, getConfig()), getConfig());
        await vscode.env.openExternal(vscode.Uri.parse(url));
      } catch (err) {
        vscode.window.showErrorMessage(
          `Ibis Settings unavailable: ${err && err.message ? err.message : err}`,
        );
      }
    }),
    vscode.commands.registerCommand("ibis.openExtensionSettings", async () => {
      await vscode.commands.executeCommand(
        "workbench.action.openSettings",
        `@ext:${EXTENSION_ID}`,
      );
    }),
    vscode.commands.registerCommand("ibis.showOutput", () => {
      outputChannel.show(true);
    }),
    vscode.commands.registerCommand("ibis.status", async () => {
      const live = getConfig();
      const selection = resolveBackendSelection(live, host);
      if (
        selection.mode === "daemon" &&
        !(await probeReachable(selection.url, probeTimeoutMs(live)))
      ) {
        const pick = await vscode.window.showErrorMessage(
          `Ibis personal daemon offline (${selection.url})`,
          "Start Daemon",
          "Details",
        );
        if (pick === "Start Daemon") {
          await startDaemon(host, live);
          return;
        }
        if (pick !== "Details") {
          return;
        }
      }
      const message = await buildStatus(host, live);
      await reportStatus(live, message);
    }),
    vscode.commands.registerCommand("ibis.startDaemon", async () => {
      try {
        await startDaemon(host, getConfig());
      } catch (err) {
        vscode.window.showErrorMessage(
          `Ibis Start Daemon failed: ${err && err.message ? err.message : err}`,
        );
      }
    }),
    vscode.commands.registerCommand("ibis.remember", async () => {
      try {
        await rememberMemory(host, getConfig());
      } catch (err) {
        vscode.window.showErrorMessage(
          `Ibis Remember failed: ${err && err.message ? err.message : err}`,
        );
      }
    }),
    vscode.commands.registerCommand("ibis.setWorkingState", async () => {
      try {
        await setWorkingState(host, getConfig());
      } catch (err) {
        vscode.window.showErrorMessage(
          `Ibis Set working state failed: ${err && err.message ? err.message : err}`,
        );
      }
    }),
    vscode.workspace.onDidChangeConfiguration((event) => {
      if (event.affectsConfiguration("ibis")) {
        refreshStatusBar(host);
      }
      if (event.affectsConfiguration("ibis.runtime")) {
        // Runtime identity changed (binary/mode/data dir/args): persistent
        // ide-host sessions must not survive it.
        host.disposeMcpSessions?.();
      }
      const reloadKeys = [
        "ibis.lmBridge.enabled",
        "ibis.lmBridge.port",
        "ibis.lmBridge.url",
        "ibis.mcp.registerProvider",
      ];
      if (reloadKeys.some((key) => event.affectsConfiguration(key))) {
        vscode.window.showInformationMessage(
          "Ibis Assistant: reload the window to apply the changed Ibis settings.",
        );
      }
    }),
  );

  logLine(
    `activated (ide-host: ${host.source}, engine: ${vscode.version}, ibis: ${context.extension.packageJSON.version}); run "Ibis Assistant: Status" for the effective backend`,
  );
  logVerbose(
    cfg,
    `configured modes: runtime=${cfg.get("runtime.mode")}, runtimeMode=${cfg.get("runtime.runtimeMode")}, ` +
      `autoAttach=${cfg.get("runtime.autoAttach")}, lmBridge=${cfg.get("lmBridge.enabled")}, ` +
      `statusOutput=${cfg.get("status.outputMode")}`,
  );
}

/**
 * Backend selection without probing (F4 §A.1):
 * - `daemon` (runtime.mode `auto`, the default): attach to the always-on
 *   personal daemon — `IBIS_MCP_URL` overrides the endpoint, else the
 *   explicit `runtime.mcpUrl`, else `DEFAULT_MCP_URL`.
 * - `attach`: explicit endpoint pin via `runtime.mcpUrl`/`IBIS_MCP_URL`.
 * - `spawn`: legacy isolated child (explicit selection only, bit-for-bit).
 * @param {vscode.WorkspaceConfiguration} cfg
 * @param {{ DEFAULT_MCP_URL: string }} host
 * @returns {{ mode: "daemon" | "attach" | "spawn", url: string }}
 */
function resolveBackendSelection(cfg, host) {
  const mode = cfg.get("runtime.mode", "auto");
  if (mode === "spawn") {
    return { mode: "spawn", url: "" };
  }
  const url = String(
    settingOrEnv(cfg, "runtime.mcpUrl", "IBIS_MCP_URL", "") || host.DEFAULT_MCP_URL,
  ).trim();
  return { mode: mode === "attach" ? "attach" : "daemon", url: url || host.DEFAULT_MCP_URL };
}

/** Probe timeout shared by daemon/auto-attach/settings checks. */
function probeTimeoutMs(cfg) {
  return cfg.get("settings.probeTimeoutMs", 800);
}

/**
 * @param {string} url
 * @param {number} timeoutMs
 */
async function probeReachable(url, timeoutMs) {
  try {
    const res = await fetch(url, { method: "GET", signal: AbortSignal.timeout(timeoutMs) });
    // The MCP endpoint may answer GET with an open SSE stream: drop the body
    // right away so repeated probes never leak connections.
    try {
      await res.body?.cancel();
    } catch {
      /* already closed */
    }
    return true;
  } catch {
    return false;
  }
}

/**
 * Environment handed to a spawned child, derived from Ibis settings + env.
 * @param {vscode.WorkspaceConfiguration} cfg
 */
function buildSpawnEnv(cfg) {
  const env = { ...process.env };
  const binary = String(settingOrEnv(cfg, "runtime.binaryPath", "IBIS_BIN", "")).trim();
  if (binary) {
    env.IBIS_BIN = binary;
  }
  const dataDir = String(settingOrEnv(cfg, "runtime.dataDir", "IBIS_DATA_DIR", "")).trim();
  if (dataDir) {
    env.IBIS_DATA_DIR = dataDir;
  }
  let workspace = String(
    settingOrEnv(cfg, "runtime.workspaceOverride", "IBIS_WORKSPACE", ""),
  ).trim();
  if (!workspace) {
    const folder = vscode.workspace.workspaceFolders && vscode.workspace.workspaceFolders[0];
    if (folder) {
      workspace = folder.uri.fsPath;
    }
  }
  if (workspace) {
    env.IBIS_WORKSPACE = workspace;
  }
  return env;
}

/**
 * Resolve the effective backend from settings, env, and optional auto-attach probe.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 * @returns {Promise<{ mode: "spawn"; command: string; args: string[]; env: NodeJS.ProcessEnv } | { mode: "http"; url: string }>}
 */
async function resolveBackend(host, cfg) {
  const selection = resolveBackendSelection(cfg, host);
  if (selection.mode !== "spawn") {
    logVerbose(cfg, `backend: ${selection.mode} ${selection.url}`);
    return { mode: "http", url: selection.url };
  }

  if (cfg.get("runtime.autoAttach", false)) {
    for (const url of cfg.get("runtime.autoAttachProbeUrls", []) || []) {
      if (await probeReachable(url, probeTimeoutMs(cfg))) {
        logVerbose(cfg, `backend: auto-attach ${url} (reachable)`);
        return { mode: "http", url };
      }
    }
  }

  const env = buildSpawnEnv(cfg);
  const backend = host.resolveBackend(env);
  if (backend.mode === "spawn") {
    const runtimeMode = cfg.get("runtime.runtimeMode", "plugin");
    const extraArgs = (cfg.get("runtime.extraArgs", []) || []).filter(
      (arg) => typeof arg === "string" && arg.trim().length > 0,
    );
    backend.args = ["-mode", "stdio", "-runtime-mode", runtimeMode, ...extraArgs];
    backend.env = { ...env, RUNTIME_MODE: runtimeMode };
  }
  logVerbose(cfg, `backend: spawn ${backend.command} ${backend.args.join(" ")}`);
  return backend;
}

/**
 * Pay the plugin boot at activation instead of on the first tree
 * interaction (S1.3 cold target): fire-and-forget spawn of the persistent
 * session child — MCP handshake + one cheap read-only call — so the
 * SurrealDB sidecar boot (1.4–4.9s, up to ~17s with Ollama down) is paid
 * during VS Code startup. The null call mirrors the tree's phrase-B fetch
 * shape (a `memory_list` core tool: ticketing tools are not announced
 * without a configured provider and the runtime rejects them). The first
 * real interaction reuses this warm session; a failure only means the boot
 * is paid later, transparently.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 */
function prewarmRuntime(host, cfg) {
  resolveBackend(host, cfg)
    .then((backend) => {
      if (backend.mode !== "spawn") {
        return;
      }
      const started = Date.now();
      host
        .callMcpTool(backend, "memory_list", { kind: "decision", limit: 1 })
        .then(() =>
          logLine(
            `pre-warm: runtime session ready in ${Date.now() - started}ms (boot paid at activation)`,
          ),
        )
        .catch((err) =>
          logLine(
            `pre-warm failed after ${Date.now() - started}ms: ${err && err.message ? err.message : err}`,
          ),
        );
    })
    .catch((err) => logLine(`pre-warm skipped: ${err && err.message ? err.message : err}`));
}

/**
 * One-shot child run with captured output (used for `ibis start`); resolves
 * with `code: null` on spawn error or timeout.
 * @param {string} binary
 * @param {string[]} args
 * @param {NodeJS.ProcessEnv} env
 * @param {number} timeoutMs
 * @returns {Promise<{ code: number | null, output: string }>}
 */
function runOneShot(binary, args, env, timeoutMs) {
  return new Promise((resolve) => {
    /** @type {string[]} */
    const chunks = [];
    let settled = false;
    const child = spawn(binary, args, {
      env,
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
    });
    const finish = (code) => {
      if (settled) {
        return;
      }
      settled = true;
      clearTimeout(timer);
      resolve({ code, output: chunks.join("").trim() });
    };
    const timer = setTimeout(() => {
      try {
        child.kill();
      } catch {
        /* ignore */
      }
      finish(null);
    }, timeoutMs);
    child.stdout?.on("data", (chunk) => chunks.push(String(chunk)));
    child.stderr?.on("data", (chunk) => chunks.push(String(chunk)));
    child.on("error", (err) => {
      chunks.push(String(err && err.message ? err.message : err));
      finish(null);
    });
    child.on("exit", (code) => finish(code));
  });
}

/**
 * Start the personal daemon: one-shot `<binary> start` — the runtime's own
 * PID-file daemon verb, which spawns `ibis run` detached (stdout/stderr to
 * server.log next to the binary) so the daemon outlives VS Code — then
 * re-probe the MCP endpoint. If the host job refuses the breakaway or the
 * daemon never comes up, fall back to instructing a manual start.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 */
async function startDaemon(host, cfg) {
  const selection = resolveBackendSelection(cfg, host);
  const url = selection.mode === "spawn" ? host.DEFAULT_MCP_URL : selection.url;
  const binary =
    String(settingOrEnv(cfg, "runtime.binaryPath", "IBIS_BIN", "ibis")).trim() || "ibis";

  const report = await vscode.window.withProgress(
    {
      location: vscode.ProgressLocation.Notification,
      title: `Ibis: starting personal daemon ("${binary} start")…`,
    },
    async () => {
      logLine(`start daemon: spawning "${binary} start" (daemon endpoint ${url})`);
      const res = await runOneShot(binary, ["start"], buildSpawnEnv(cfg), 20_000);
      if (res.output) {
        logLine(
          `start daemon: exit=${res.code === null ? "error/timeout" : res.code} — ${
            res.output.replace(/\s+/g, " ").slice(0, 400)
          }`,
        );
      }
      if (res.code === null) {
        return {
          ok: false,
          detail: `"${binary} start" failed to run (${res.output || "spawn error or timeout"})`,
        };
      }
      // The PID file lands immediately, but the daemon boots its SurrealDB
      // sidecar before the MCP endpoint answers: re-probe for up to ~15s.
      const deadline = Date.now() + 15_000;
      while (Date.now() < deadline) {
        if (await probeReachable(url, probeTimeoutMs(cfg))) {
          return { ok: true, detail: res.output };
        }
        await new Promise((resolve) => setTimeout(resolve, 500));
      }
      return { ok: false, detail: res.output || `endpoint ${url} never answered` };
    },
  );

  await refreshStatusBar(host);
  if (report.ok) {
    logLine(`start daemon: reachable at ${url}`);
    await vscode.window.showInformationMessage(`Ibis personal daemon started (${url})`);
  } else {
    logLine(`start daemon failed: ${report.detail}`);
    await vscode.window.showErrorMessage(
      `Ibis daemon still offline: ${report.detail}. Start it manually: "${binary} start" or "${binary} run" in a terminal.`,
    );
  }
}

/**
 * Start the IDE LM bridge when enabled and vscode.lm is available.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 */
async function startLmBridge(host, cfg) {
  if (!cfg.get("lmBridge.enabled", true)) {
    logLine("LM bridge disabled by ibis.lmBridge.enabled");
    return;
  }
  try {
    const family = String(cfg.get("lmBridge.modelFamily", "")).trim();
    const attached = await host.attachVscodeLm(vscode, { family });
    if (!attached) {
      logLine("LM bridge not started: vscode.lm is unavailable in this host");
      return;
    }
    const explicitPort = isExplicitlyConfigured(cfg, "lmBridge.port")
      ? cfg.get("lmBridge.port", host.LM_BRIDGE_DEFAULT_PORT)
      : Number(process.env.IBIS_LM_BRIDGE_PORT || cfg.get("lmBridge.port", host.LM_BRIDGE_DEFAULT_PORT));
    const port = explicitPort || host.LM_BRIDGE_DEFAULT_PORT;
    lmServer = await host.startLmRpcServer({ port });
    const url = String(settingOrEnv(cfg, "lmBridge.url", "IBIS_LM_BRIDGE_URL", "")).trim() ||
      `http://127.0.0.1:${port}`;
    process.env.IBIS_LM_BRIDGE_URL = url;
    logLine(`LM bridge listening on ${url}${family ? ` (model family: ${family})` : ""}`);
  } catch (err) {
    logLine(`LM bridge not started: ${err && err.message ? err.message : err}`);
  }
}

/**
 * Register the contributed MCP server-definition provider (VS Code 1.101+).
 * Definitions are recomputed from live settings on every request.
 * @param {vscode.ExtensionContext} context
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 */
function registerMcpProvider(context, host) {
  const cfg = getConfig();
  if (!cfg.get("mcp.registerProvider", true)) {
    logLine("MCP server definition provider disabled by ibis.mcp.registerProvider");
    return;
  }
  const lm = vscode.lm;
  if (!lm || typeof lm.registerMcpServerDefinitionProvider !== "function") {
    logLine("MCP server definition provider unavailable (VS Code < 1.101)");
    return;
  }

  const provider = {
    provideMcpServerDefinitions: async () => {
      const defs = [];
      let backend;
      try {
        backend = await resolveBackend(host, getConfig());
      } catch (err) {
        logLine(`MCP definition resolution failed: ${err && err.message ? err.message : err}`);
        return defs;
      }
      if (backend.mode === "http" && backend.url) {
        if (typeof vscode.McpHttpServerDefinition === "function") {
          defs.push(new vscode.McpHttpServerDefinition("Ibis", vscode.Uri.parse(backend.url)));
        } else if (typeof vscode.McpServerDefinition === "function") {
          defs.push({ label: "Ibis", uri: vscode.Uri.parse(backend.url) });
        }
        return defs;
      }
      if (typeof vscode.McpStdioServerDefinition === "function") {
        defs.push(
          new vscode.McpStdioServerDefinition(
            "Ibis",
            backend.command,
            backend.args,
            { ...(backend.env || {}) },
          ),
        );
      }
      return defs;
    },
  };

  try {
    context.subscriptions.push(lm.registerMcpServerDefinitionProvider("ibis", provider));
    mcpProviderRegistered = true;
    logLine("MCP server definition provider registered");
  } catch (err) {
    logLine(
      `MCP server definition provider not registered: ${err && err.message ? err.message : err}`,
    );
  }
}

/**
 * Durable decision/fix/rule capture via MCP memory_add.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 */
async function rememberMemory(host, cfg) {
  const kinds = REMEMBER_KINDS;

  let kind = cfg.get("memory.defaultKind", "ask");
  if (kind === "ask") {
    const kindPick = await vscode.window.showQuickPick(kinds, {
      placeHolder: "Memory kind",
      title: "Ibis Assistant: Remember",
    });
    if (!kindPick) {
      return;
    }
    kind = kindPick.label;
  }

  const title = await vscode.window.showInputBox({
    title: "Ibis Assistant: Remember",
    prompt: `Short title (${kind})`,
    placeHolder: "e.g. Prefer Streamable HTTP for MCP",
  });
  if (title === undefined) {
    return;
  }
  const content = await vscode.window.showInputBox({
    title: "Ibis Assistant: Remember",
    prompt: "Full memory content",
    placeHolder: "What should future agents and teammates reuse?",
    ignoreFocusOut: true,
  });
  if (!content || !content.trim()) {
    return;
  }

  const visibility = cfg.get("memory.defaultVisibility", "team");
  const backend = await resolveBackend(host, cfg);
  const text = await host.callMcpTool(backend, "memory_add", {
    kind,
    title: title.trim(),
    content: content.trim(),
    visibility,
  });
  logLine(`memory_add (${kind}, ${visibility}): ${text}`);
  await vscode.commands.executeCommand("ibis.memory.refresh");
  vscode.window.showInformationMessage(`Ibis Remembered (${kind}, ${visibility}): ${text}`);
}

/**
 * Current-task upsert via MCP set_working_state.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 */
async function setWorkingState(host, cfg) {
  const content = await vscode.window.showInputBox({
    title: "Ibis Assistant: Set working state",
    prompt: "What are you working on right now?",
    placeHolder: "Current task, open files, next steps",
    ignoreFocusOut: true,
  });
  if (!content || !content.trim()) {
    return;
  }
  /** @type {Record<string, string>} */
  const args = { content: content.trim() };
  if (cfg.get("workingState.useWorkspaceProject", true)) {
    const folder = vscode.workspace.workspaceFolders && vscode.workspace.workspaceFolders[0];
    if (folder) {
      args.project_name = folder.name;
    }
  }
  const backend = await resolveBackend(host, cfg);
  const text = await host.callMcpTool(backend, "set_working_state", args);
  logLine(`set_working_state${args.project_name ? ` (${args.project_name})` : ""}: ${text}`);
  vscode.window.showInformationMessage(`Ibis working state set: ${text}`);
}

/**
 * Prefer ibis.settings.url / IBIS_SETTINGS_URL, then personal HTTP probes,
 * else MCP settings_open_ui.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {{ mode: string, url?: string, command?: string, args?: string[], env?: NodeJS.ProcessEnv }} backend
 * @param {vscode.WorkspaceConfiguration} [cfg]
 */
async function resolveSettingsURL(host, backend, cfg = getConfig()) {
  const explicit = String(settingOrEnv(cfg, "settings.url", "IBIS_SETTINGS_URL", "")).trim();
  if (explicit) {
    return explicit;
  }
  const timeoutMs = cfg.get("settings.probeTimeoutMs", 800);
  for (const base of cfg.get("settings.probeUrls", []) || []) {
    try {
      const res = await fetch(base, { signal: AbortSignal.timeout(timeoutMs) });
      if (res.ok) {
        return base;
      }
    } catch {
      /* probe next */
    }
  }
  // settings_open_ui hosts the ephemeral loopback listener inside the child
  // process: a one-shot spawn child must stay alive after the tool call, or
  // the browser hits ERR_CONNECTION_REFUSED. 20 min = the runtime's own
  // ephemeral idle timeout. Attach mode needs no keep-alive (the shared
  // runtime hosts the listener).
  const text = await host.callMcpTool(
    backend,
    "settings_open_ui",
    {},
    backend.mode === "spawn" ? { keepAliveMs: 20 * 60 * 1000 } : {},
  );
  const url = host.extractSettingsURL(text);
  if (!url) {
    throw new Error("settings_open_ui did not return a URL");
  }
  return url;
}

/**
 * Status bar item: backend mode (spawn/attach) plus LM-bridge and MCP-provider
 * indicators. Click runs the Status command; refreshed on any `ibis.*` change.
 * @param {vscode.ExtensionContext} context
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 */
function createStatusBarItem(context, host) {
  const item = vscode.window.createStatusBarItem(vscode.StatusBarAlignment.Right, 100);
  item.name = "Ibis Assistant";
  item.command = "ibis.status";
  context.subscriptions.push(item);
  statusBarItem = item;
  refreshStatusBar(host);
}

/**
 * Re-render the status bar from live settings and current bridge/provider state.
 * Daemon mode probes the endpoint: reachable renders as `Ibis attach`,
 * unreachable as `$(error) Ibis daemon offline` (F4 §A.1).
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 */
async function refreshStatusBar(host) {
  if (!statusBarItem) {
    return;
  }
  const cfg = getConfig();
  const selection = resolveBackendSelection(cfg, host);
  if (selection.mode === "daemon") {
    const reachable = await probeReachable(selection.url, probeTimeoutMs(cfg));
    if (!reachable) {
      statusBarItem.text = `$(error) Ibis daemon offline`;
      statusBarItem.tooltip = `Personal daemon unreachable at ${selection.url}.\nClick for details; run "Ibis Assistant: Start Daemon".`;
      statusBarItem.show();
      return;
    }
  }
  let backend;
  try {
    backend = await resolveBackend(host, cfg);
  } catch (err) {
    statusBarItem.text = `$(error) Ibis`;
    statusBarItem.tooltip = `Ibis Assistant backend error: ${err && err.message ? err.message : err}`;
    statusBarItem.show();
    return;
  }
  const attach = backend.mode === "http";
  const parts = [`${attach ? "$(cloud)" : "$(terminal)"} Ibis ${attach ? "attach" : "spawn"}`];
  if (cfg.get("lmBridge.enabled", true) && lmServer) {
    parts.push("$(zap)");
  }
  if (cfg.get("mcp.registerProvider", true) && mcpProviderRegistered) {
    parts.push("$(check)");
  }
  statusBarItem.text = parts.join(" ");
  statusBarItem.tooltip = await buildStatus(host, cfg);
  statusBarItem.show();
}

/**
 * Human-readable status for the Ibis: Status command.
 * @param {Awaited<ReturnType<typeof loadIdeHost>>} host
 * @param {vscode.WorkspaceConfiguration} cfg
 */
async function buildStatus(host, cfg) {
  const lines = [];
  const selection = resolveBackendSelection(cfg, host);
  if (selection.mode === "daemon") {
    const reachable = await probeReachable(selection.url, probeTimeoutMs(cfg));
    lines.push(
      reachable
        ? `Personal daemon: reachable at ${selection.url} (shared runtime)`
        : `Personal daemon: OFFLINE at ${selection.url} — run "Ibis Assistant: Start Daemon" (or "ibis start" / "ibis run" in a terminal)`,
    );
    lines.push("Daemon lifecycle: ibis start / ibis stop (background, PID file, server.log)");
  } else {
    const backend = await resolveBackend(host, cfg);
    if (backend.mode === "http") {
      lines.push(`Backend: attach ${backend.url} (shared runtime)`);
    } else {
      lines.push(`Backend: spawn ${backend.command} (isolated child)`);
      lines.push(`Runtime args: ${backend.args.join(" ")}`);
    }
    lines.push(`Plugin data dir: ${(backend.mode === "spawn" && backend.env.IBIS_DATA_DIR) || "default"}`);
    lines.push(`Workspace: ${(backend.mode === "spawn" && backend.env.IBIS_WORKSPACE) || "not bound"}`);
  }
  if (!cfg.get("lmBridge.enabled", true)) {
    lines.push("IDE LM bridge: disabled (ibis.lmBridge.enabled)");
  } else {
    lines.push(
      `IDE LM bridge: ${lmServer ? `listening (${process.env.IBIS_LM_BRIDGE_URL})` : "unavailable"}`,
    );
  }
  lines.push(
    `MCP provider: ${
      !cfg.get("mcp.registerProvider", true)
        ? "disabled"
        : mcpProviderRegistered
          ? "registered"
          : "unavailable"
    }`,
  );
  lines.push(`Memory default: ${cfg.get("memory.defaultKind", "ask")}/${cfg.get("memory.defaultVisibility", "team")}`);
  lines.push(
    "For agents: call load_session_context once per session; capture only genuinely new, reusable observations. Call MCP ticket_get_capabilities / settings_get for full readiness.",
  );
  return lines.join("\n");
}

/**
 * Toast shows only the compact summary (first line) with actions; the full
 * structured status always lands in the output channel (the toast cannot
 * render line breaks — it was a wall of text).
 * @param {vscode.WorkspaceConfiguration} cfg
 * @param {string} message
 */
async function reportStatus(cfg, message) {
  const mode = cfg.get("status.outputMode", "toast");
  const full = "status:\n" + message;
  if (mode === "output" || mode === "both") {
    logLine(full);
    if (outputChannel) {
      outputChannel.show(true);
    }
  }
  if (mode === "toast" || mode === "both") {
    const summary = message.split("\n").filter(Boolean)[0] || "Ibis Assistant";
    const pick = await vscode.window.showInformationMessage(
      summary,
      "Details",
      "Open Settings",
    );
    if (pick === "Details") {
      logLine(full);
      if (outputChannel) {
        outputChannel.show(true);
      }
    } else if (pick === "Open Settings") {
      await vscode.commands.executeCommand("ibis.openExtensionSettings");
    }
  }
}

/**
 * @param {{ mode: string, url?: string, command?: string, args?: string[] }} backend
 */
function sharedRuntimeMcpConfig(backend) {
  if (backend.mode === "http") {
    return { ibis: { url: backend.url } };
  }
  return {
    ibis: {
      command: backend.command || "ibis",
      args: backend.args || ["-mode", "stdio", "-runtime-mode", "plugin"],
      env: { RUNTIME_MODE: "plugin" },
    },
  };
}

function deactivate() {
  try {
    hostDispose?.();
  } catch {
    /* ignore */
  }
  if (lmServer) {
    lmServer.close();
    lmServer = undefined;
  }
}

/** @type {(() => void) | undefined} */
let hostDispose;

/** Keep the deactivate path able to close ide-host sessions. */
function bindHostDispose(host) {
  hostDispose = host?.disposeMcpSessions?.bind(host);
}

module.exports = { activate, deactivate, sharedRuntimeMcpConfig, resolveSettingsURL };
