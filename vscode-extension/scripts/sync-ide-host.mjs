/**
 * Vendor ../ide-host/src into vendor/ide-host for the packaged VSIX.
 *
 * `file:` dependencies are not reliably packaged by vsce (the VSIX ships with
 * `--no-dependencies`), so the extension falls back to this generated copy when
 * the @threski/ide-host package import is unavailable.
 * Runs automatically via the vscode:prepublish npm script.
 */

import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const extensionRoot = dirname(here);
const sourceRoot = join(extensionRoot, "..", "ide-host", "src");
const vendorRoot = join(extensionRoot, "vendor", "ide-host");

const files = ["index.js", "lm-bridge.js", "lm-rpc.js"];

rmSync(vendorRoot, { recursive: true, force: true });
mkdirSync(vendorRoot, { recursive: true });
for (const file of files) {
  cpSync(join(sourceRoot, file), join(vendorRoot, file));
}
writeFileSync(
  join(vendorRoot, "package.json"),
  `${JSON.stringify({ name: "@threski/ide-host-vendor", private: true, type: "module" }, null, 2)}\n`,
);
writeFileSync(
  join(vendorRoot, "README.md"),
  "Generated by scripts/sync-ide-host.mjs from ../ide-host/src at package time. Do not edit.\n",
);

console.log(`[threski] vendored ide-host (${files.join(", ")}) -> ${vendorRoot}`);
